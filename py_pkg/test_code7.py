# 結果を保存するCSVファイルのパスを決める関数
def resolve_csv_file():
    """既存ファイルへ追記するか、新規作成するかをGUIで選ばせる"""
    root = tk.Tk()                                                                                  # Tkのルートウィンドウ
    root.withdraw()                                                                                 # ウィンドウ自体は表示しない（ダイアログだけ使う）
    print("【結果を保存するCSVファイル】 1: 既存ファイルへ追記 / 2: 新規作成")
    mode = input("> ").strip()                                                                      # 保存方法の選択
    while mode not in ['1', '2']:
        mode = input("無効な入力です。1 または 2 を入力してください: ").strip()

    if mode == '1':                                                                                 # 既存ファイルへ追記する場合
        path = filedialog.askopenfilename(title="追記するCSVファイルを選択してください",
                                          filetypes=[("CSV", "*.csv")])
        if not path:
            print("ファイル未選択のため終了します。")
            sys.exit(1)
        return path

    folder_path = filedialog.askdirectory(title="結果のCSVファイルを保存するフォルダを選択してください")  # フォルダ選択ダイアログを表示
    if not folder_path:
        print("フォルダ未選択のため終了します。")
        sys.exit(1)
    file_name = input("新規作成するCSVファイル名を入力してください (例: result.csv): ").strip()          # ファイル名の入力
    if not file_name.endswith(".csv"):
        file_name += ".csv"
    return os.path.join(folder_path, file_name)


def main(args=None):
    csv_path = resolve_csv_file()                                                                   # 保存先CSVのパスを決める
    print(f"【保存先CSVパス】 {csv_path}")

    print("【FF制御時間 T を入力してください】")
    T = float(input("> "))                                                                          # FF制御入力時間 [s]
    print("【最適制御実行回数（外側ループ）を入力してください】")
    max_iter = int(input("> "))                                                                     # 外側ループの最大回数
    print("【モードを選択してください (1: プリセット後ランダム, 2: 最初からランダム)】")
    mode = input("> ").strip()                                                                      # 目標値の与え方
    while mode not in ['1', '2']:
        mode = input("無効な入力です。1 または 2 を入力してください: ").strip()

    rclpy.init(args=args)                                                                           # ROS2の初期化
    node = OptimalControlSequencer(csv_path, T, max_iter, mode)                                     # ノードの生成
    # 購読（15トピック）とシーケンサのタイマーを別スレッドで動かす。
    #   単一スレッドだと、FF送信・ログ出力・sleep のあいだ受信が止まり、その間のデータが
    #   受信キューから溢れて消える。消えた区間は補間で直線に化けるため、実機が振動していても
    #   グラフが水平になってしまう。
    executor = MultiThreadedExecutor(num_threads=17)                                                # 購読15（POT5+PWM5+z3を5） + タイマー1 + 余裕1
    executor.add_node(node)
    try:
        while rclpy.ok() and not node.shutdown_event.is_set():                                      # 終了要求が来るまで回し続ける
            executor.spin_once(timeout_sec=0.1)
    except KeyboardInterrupt:
        pass
    finally:
        executor.shutdown()
        node.destroy_node()
        if rclpy.ok():
            rclpy.shutdown()


if __name__ == '__main__':
    main()
