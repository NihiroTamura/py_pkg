#                             → 「振動を防ぎながら目標軌道・目標位置に一致させることを最重要」
#       k_s = 目標軌道が ±SETTLE_BAND·|step| の帯へ入って以降出てこなくなる最初のインデックス
#
#   なぜ時刻での切替なのか（理論上の要点）
