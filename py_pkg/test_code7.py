    # 目標軌道の整定インデックス k_s を求める関数
    def settle_index(self, z_tgt, step, band=SETTLE_BAND):                                          # 引数(z形式の目標軌道, 目標変位 Pf-Pi, 整定判定の帯幅)
        """k_s = min{ k : |z_tgt(j) - step| <= band·|step|  ∀ j >= k } を返す。

        z_tgt は目標モデルの応答であって最適化変数 u に依存しない既知の固定信号なので、k_s は
        定数である。したがって Q_k の切替は「時刻インデックスに対する切替」であって「状態に対する
        切替」ではなく、J は u について厳密な二次形式のままになる（随伴方程式の形が変わらない）。

        フォールバック（実装時に忘れやすい）
          ・目標軌道が評価ホライズン内で帯へ入らない場合は k_s = M を返す（整定区間なし）。
            素朴に next(...) で書くと StopIteration を投げるので必ずここで処理する。
          ・|step| が極小の自由度では band·|step| が数値ノイズ以下になり k_s が意味を持たない。
            そのような自由度は呼び出し側で STEP_MIN によって最適化対象から外すこと。
        """
        M = len(z_tgt)                                                                              # 評価ホライズンのサンプル数
        tol = float(band) * abs(float(step))                                                        # 帯の半幅 [count]
        if not np.isfinite(tol) or tol <= 0.0:                                                      # 目標変位がゼロ・異常な場合
            return M                                                                                # 整定区間なしとして扱う
        inside = np.abs(np.asarray(z_tgt, dtype=float) - float(step)) <= tol                        # 各時刻が帯の中にあるか
        k_s = M                                                                                     # 「以降ずっと帯の中」の最初の位置（既定は整定区間なし）
        for k in range(M - 1, -1, -1):                                                              # 末尾から走査する
            if not inside[k]:                                                                       # 帯の外に出た時点で打ち切る
                break
            k_s = k                                                                                 # そこまでは「以降ずっと帯の中」
        return k_s

    # 時変の状態重み列 Q_k を作る関数
    def build_q_seq(self, k_s, M):                                                                  # 引数(整定区間の開始インデックス, 評価ホライズンのサンプル数)
        """k < k_s は Q_pre（過渡区間）、k >= k_s は Q_post（整定区間）の重み行列を並べる。

        過渡区間は位置の重みを小さく・速度と加速度の重みを相対的に大きくして
        「目標軌道への厳密追従より、振動のない滑らかな応答」を優先する。
        整定区間はすべて大きくして「振動を防ぎながら目標軌道・目標位置に一致」を最重要にする。
        """
        Q_seq = np.empty((M, 3, 3))                                                                 # 時刻ごとの重み行列
        k_s = int(np.clip(k_s, 0, M))                                                               # 範囲外の k_s を丸める
        Q_seq[:k_s] = self.Q_pre                                                                    # 過渡区間の重み
        Q_seq[k_s:] = self.Q_post                                                                   # 整定区間の重み
        return Q_seq

    # ------------------------------------------------------------------
    # 離散時間オイラー・ラグランジュ（随伴／勾配）法による最適制御 + 5次多項式フィット
    # ------------------------------------------------------------------

    # 目標軌道を z 形式で生成する関数
    def build_target_traj(self, target_params, y0, step):                                           # 引数(目標モデルのパラメータ[T1, wn], 初期偏差 Pi-Pf, 目標変位 Pf-Pi)
        """目標モデルの自由応答を z = P - Pi の系へオフセットして目標軌道 x_tgt(k) を作る。

        目標モデルの同定は誤差系（y = P - Pf, y0 → 0 へ収束する自由応答）で行うが、最適制御では
        システムモデル同定と同じ z = P - Pi の系（z(0)=0 → step へ立ち上がる）で扱う。
        両者は定数オフセットの関係にあり、z_tgt(k) = y_tgt(k) - y0 が厳密に成り立つ
        （3次系は相対次数3なので、step応答 z は自由応答 y の1-補数 z = step(1 - y/y0), step = -y0。
          位置成分だけがオフセットされ、速度・加速度成分は自由応答のまま変わらない）。
        この座標系では x_sys(0)=x_tgt(0)=0 となり、入力規約も同定と同じ u = u_total - u_hold でそろう。

        戻り値: (x_tgt (M+1,3), y_tgt (M,))。y_tgt は呼び出し側の規約（誤差系）のまま返す。
        """
        T1, wn = target_params                                                                      # 目標モデルのパラメータ取得
        a2_tgt, a1_tgt, a0_tgt = self._target_coeffs(T1, wn)                                        # 目標モデルの3次遅れ系の係数を計算
        A_tgt, _ = self._discretize(a2_tgt, a1_tgt, a0_tgt, 0.0)                                    # 目標モデルのZOH離散状態方程式（u=0）
        M = self.M                                                                                  # 評価ホライズンのサンプル数
        x_tgt = np.zeros((M + 1, 3))                                                                # 目標状態列 x_tgt(0..M)（e(M) までコストに使えるよう M+1 点）
        x_tgt[0] = np.array([y0, 0.0, 0.0])                                                         # 誤差系での初期状態（自由応答の初期値）
        for k in range(M):                                                                          # 目標モデルの自由応答を逐次計算
            x_tgt[k + 1] = A_tgt @ x_tgt[k]                                                         # x_tgt(k+1) = A_tgt x_tgt(k)
        y_tgt = x_tgt[:M, 0].copy()                                                                 # 目標出力（誤差系 y0→0）。呼び出し側の規約は維持する
        x_tgt[:, 0] += step                                                                         # 位置成分だけを z 形式へオフセット（x_tgt(0)の位置=0, 最終値=step）
        return x_tgt, y_tgt

    # 離散時間オイラー・ラグランジュ法で最適FF入力を計算し、5次関数へ近似する関数
    def calculate_el_ff(self, target_params, sys_params, y0, adrc_params, u_hold,                   # 引数(目標モデルのパラメータ[T1, wn], システムモデルのパラメータ[T1, zeta, wn, b0], 初期偏差 Pi-Pf, ADRCパラメータ(kp,kd,input_coef,λ₀), 初期姿勢の保持PWM)
                         z3_init=None, u_max=PWM_LIMIT):                                            # 引数(実測 z3(0⁻), FF振幅の上限[PWM])
        """ADRCを含む閉ループに対して u_FF を最適化し、5次多項式 f(t) へ近似する。

        目的：システムモデルの軌道を、目標モデルが描く目標軌道 x_tgt へ一致させる。
          座標系       : z = P - Pi（初期位置を原点とする系）。入力は u = u_total - u_hold
          入力の分解   : u(k) = ( u_ADRC(k) - u_hold ) + u_FF(k)
                         u_ADRC は実測から与えるのではなく、この関数の中でADRCを逐次計算して得る。
                         最適化変数は u_FF だけであり、u_ADRC にコストは掛けない。
          入力ホライズン : u_FF(k) は [0,T)（k=0..N_ff-1）のみ最適化し、それ以降は0。
                         k >= N_ff では u(k) = u_ADRC(k) - u_hold となり、ADRCだけが姿勢を保持する。
                         この区間は評価ホライズン全体の約70%（455ステップ中318ステップ）を占め、
                         「FFを切った後にADRCで動いた状態」と目標軌道の誤差がここで評価される。
          端点条件     : u_FF(0) = 0 をハード制約、u_FF(N_ff) = 0 はレート罰則の境界で誘導する
          評価ホライズン : コスト J はシミュレーション全体（k=0..M-1）で評価する

        ● ADRCを内部に含む閉ループ系（詳細は _adrc_closed_loop() を参照）
            ξ(k+1) = A_cl ξ(k) + B_cl u_FF(k) + c_cl,   x_sys(k) = S ξ(k)
            ADRCはPD＋線形オブザーバなので閉ループ全体がアフィン系になる。したがって u_FF から
            誤差 e への写像はアフィンであり、J は u_FF の凸二次形式になる。つまり随伴方程式から
            得られる停留条件 ∂H/∂u_FF = 0 は大域最適解の必要十分条件である。

        ● コスト関数（終端コストなし）／ハミルトニアン
            J = Σ_{k=0}^{M-1} ( e(k)ᵀ Q_k e(k) )
              + Σ_{k=0}^{N_ff-1} R u_FF(k)²
              + Σ_{k=0}^{N_ff}  R_du ( u_FF(k) - u_FF(k-1) )²,  u_FF(-1)=u_FF(N_ff)=0
            段コスト L(k) = e(k)ᵀ Q_k e(k) + R u_FF(k)² + R_du ( u_FF(k)-u_FF(k-1) )²
            H(k) = L(k) + λ(k+1)ᵀ [ A_cl ξ(k) + B_cl u_FF(k) + c_cl ]
            Q が時変 Q_k になった点だけが test_code3.py との違いである。k_s は目標軌道だけから
            決まる定数なので、J は u_FF の二次形式のままであり随伴方程式の形は変わらない。
            終端コストは置かない（評価ホライズンが整定時間より十分長く、整定区間の Q_post が
            「t>k_s で静止していること」を連続的に評価するため）。

        ● 随伴方程式（λ は拡大状態と同じ6次元。レート罰則は u_FF のみの関数で ∂/∂ξ = 0）
            λ(M) = 0
            λ(k) = ∂H/∂ξ(k) = 2 Sᵀ Q_k e(k) + A_clᵀ λ(k+1)
            A_cl にはADRCのフィードバック経路が含まれるので、随伴を逆向きに解くだけで
            「u_FF を動かすとADRCがどう反応し、その反応が軌道をどう変えるか」まで勾配に入る。
            k=0 用の A_cl0 は λ(0)（未使用）にしか関与しないので、後退計算には現れない。

        ● 勾配（最適化変数 u_FF, k=0..N_ff-1）
            ∂J/∂u_FF(k) = 2 R u_FF(k) + B_clᵀ λ(k+1) + 2 R_du ( 2u_FF(k) - u_FF(k-1) - u_FF(k+1) )
            末尾の括弧は Dirichlet境界条件 u_FF(-1)=u_FF(N_ff)=0 を課した2階差分である。
            端点 k=0 は u_FF(0)=0 のハード制約なので、勾配の第0成分を0にして更新しない（射影）。

        戻り値: (ff_params[a,b,c,d,e], (t1,y1,t2,y2), u_pred_full, y_tgt, u_opt, u_ff_opt, info)
        """
        dt = self.dt                                                                                # 1ステップの刻み（実機の制御周期）
        M = self.M                                                                                  # 評価ホライズンのステップ数
        N_ff = self.N_ff                                                                            # 入力ホライズン [0,T) のステップ数
        n_x, n_xi = 3, 6                                                                            # システムモデルの状態次元・拡大状態の次元
        step = -y0                                                                                  # 目標変位 step = Pf - Pi（z形式での最終値。ADRCの目標偏差にも使う）

        # -----------------------------------------------------------
        # 同定結果から離散時間状態方程式を構築（ZOH厳密離散化、1周期＝CTRL_DT）
        # -----------------------------------------------------------
        (A_cl, B_cl, c_cl, A_cl0, c_cl0,
         xi0, u_row, u_c, u_row0, u_c0) = self._adrc_closed_loop(sys_params, adrc_params,           # ADRCを内部に含む閉ループのZOH離散状態方程式
                                                                 step, u_hold, z3_init)
        with np.errstate(all='ignore'):                                                             # 固有値計算が破綻しても最適化を止めない
            try:
                self.last_cl_radius = float(np.max(np.abs(np.linalg.eigvals(A_cl))))                # 閉ループのスペクトル半径（1以下なら安定）
            except np.linalg.LinAlgError:                                                           # 固有値が求まらない場合
                self.last_cl_radius = float('nan')

        x_tgt, y_tgt = self.build_target_traj(target_params, y0, step)                               # z形式の目標軌道と、誤差系の目標出力
        k_s = self.settle_index(x_tgt[:M, 0], step)                                                  # 目標軌道の整定インデックス（Q_k の切替時刻）
        self.last_k_s = k_s                                                                          # 呼び出し側の記録用に保存
        Q_seq = self.build_q_seq(k_s, M)                                                             # 時変の状態重み列 Q_k
        R = float(self.R[0, 0])                                                                      # FF入力の重みスカラー
        R_du = float(self.R_du)                                                                       # FF入力レート（Δu）の重みスカラー
        u_lim = float(max(u_max, U_MAX_MIN))                                                          # FF振幅の上限（トラストリージョン）

        # ---- 手順2: ADRCを含む閉ループを順方向に計算する関数 ----
        #   ξ(k+1) = A_cl ξ(k) + B_cl u_FF(k) + c_cl。A_cl の中で毎刻み
        #   「システムモデルへ入力 → 出力をESOへ渡す → 状態推定を更新 → u_ADRC を計算」が回る。
        #   k=0 だけは前周期のADRC出力が実測 u_hold なので、自己閉包を外した A_cl0 / c_cl0 を使う。
        def forward(u_seq):                                                                          # 引数(最適化変数 u_FF の列)
            xi = np.zeros((M + 1, n_xi))                                                             # 拡大状態列 ξ(0..M)
            xi[0] = xi0                                                                              # 初期状態（ζ3 には実測 z3(0⁻) が入っている）
            for k in range(M):                                                                       # k=0..M-1 を順方向に更新
                uff_k = u_seq[k] if k < N_ff else 0.0                                                # 最適化変数 u_FF(k)（FF区間の外は0）
                A_k = A_cl0 if k == 0 else A_cl                                                      # k=0 だけ自己閉包を外した写像を使う
                c_k = c_cl0 if k == 0 else c_cl                                                      # k=0 だけ実測 u_hold で閉じた定数項を使う
                xi[k + 1] = A_k @ xi[k] + B_cl * uff_k + c_k                                         # ξ(k+1)=A_cl ξ(k)+B_cl u_FF(k)+c_cl
            return xi

        # ---- 拡大状態から目標軌道との誤差 e(k) = x_sys(k) - x_tgt(k) を取り出す関数 ----
        def error_traj(xi):                                                                          # 引数(拡大状態列)
            return xi[:, :n_x] - x_tgt                                                               # 位置・速度・加速度の誤差 (M+1, 3)

        # ---- 入力レート罰則 Σ_{k=0}^{N_ff} ( u(k)-u(k-1) )² を計算する関数（u(-1)=u(N_ff)=0） ----
        #   先頭と末尾に0を1個ずつ挟んでから階差を取ることで、境界条件をそのまま式に埋め込む。
        def rate_sq(u_seq):
            du = np.diff(np.concatenate(([0.0], u_seq, [0.0])))                                      # Δu(k)=u(k)-u(k-1), k=0..N_ff（長さ N_ff+1）
            return float(du @ du)                                                                    # Σ Δu(k)²

        # ---- 入力レート罰則の勾配 (L u)(k) = 2u(k)-u(k-1)-u(k+1) を計算する関数 ----
        #   Dirichlet境界条件を課した2階差分行列 L=tridiag(-1,2,-1) との積。
        def rate_grad(u_seq):
            lu = 2.0 * u_seq.copy()                                                                  # 2u(k)
            lu[1:] -= u_seq[:-1]                                                                     # -u(k-1)（k=0 は u(-1)=0 なので引かない）
            lu[:-1] -= u_seq[1:]                                                                     # -u(k+1)（k=N_ff-1 は u(N_ff)=0 なので引かない）
            return lu

        # ---- コスト関数 J = Σ e(k)ᵀQ_k e(k) + R Σ u(k)² + R_du Σ ( u(k)-u(k-1) )² ----
        def cost(e_traj, u_seq):
            state_cost = np.einsum('ki,kij,kj->', e_traj[:M], Q_seq, e_traj[:M])                     # Σ e(k)ᵀ Q_k e(k)（時変重み）
            input_cost = R * float(np.sum(u_seq ** 2))                                               # R Σ u_FF(k)²（[0,T) のみ）
            rate_cost = R_du * rate_sq(u_seq)                                                        # R_du Σ Δu(k)²（両端は0とみなす）
            return float(state_cost + input_cost + rate_cost)

        # ---- 手順3,4: 随伴方程式を逆方向計算し λ(1..M) を求める関数 ----
        #   λ(M)=0（終端コストなし）, λ(k)=2 Sᵀ Q_k e(k)+A_clᵀ λ(k+1)
        #   λ は拡大状態と同じ6次元。状態コストは x_sys 成分だけに掛かるので、
        #   2 Q_k e(k) を先頭3成分に置き（＝Sᵀ を掛ける）、残りのオブザーバ成分は0にする。
        def backward(e_traj):
            lam = np.zeros((M + 1, n_xi))                                                            # 随伴変数列 λ(0..M)（λ(M)=0）
            qe = np.zeros(n_xi)                                                                      # 2 Sᵀ Q_k e(k) を入れる作業ベクトル
            A_T = A_cl.T                                                                             # 転置を先に作って毎回の転置を避ける
            for k in range(M - 1, 0, -1):                                                            # k=M-1..1 を逆方向に更新（λ(0)は使わない）
                qe[:n_x] = 2.0 * (Q_seq[k] @ e_traj[k])                                              # 状態コストの寄与（x_sys 成分のみ・時変重み）
                lam[k] = qe + A_T @ lam[k + 1]                                                       # λ(k)=2 Sᵀ Q_k e(k)+A_clᵀ λ(k+1)
            return lam

        # ---- 手順5: 勾配（入力ホライズン k=0..N_ff-1） ----
        def gradient(u_seq, lam):
            g = (2.0 * R * u_seq                                                                     # 入力そのものの罰則 2 R u_FF(k)
                 + lam[1:N_ff + 1] @ B_cl                                                            # 随伴からの寄与 B_clᵀ λ(k+1)（ADRCの反応は A_cl 経由で λ に入っている）
                 + 2.0 * R_du * rate_grad(u_seq))                                                    # レート罰則 2 R_du (L u_FF)(k)
            g[0] = 0.0                                                                               # 端点条件 u_FF(0)=0 は固定なので更新しない（実行可能集合への射影）
            return g

        # ---- 手順1: 最適化変数 u_FF(k) を初期化（零入力から開始） ----
        u = np.zeros(N_ff)                                                                           # 決定変数 u_FF(0..N_ff-1)（[0,T) のみ）

        # ---- 手順2〜7: 勾配降下の反復 ----
        for _ in range(EL_MAX_ITER):
            xi_traj = forward(u)                                                                     # 手順2: ADRCを含む閉ループを順方向計算
            e_traj = error_traj(xi_traj)                                                             # 目標軌道との誤差 e(k)=x_sys(k)-x_tgt(k)
            J0 = cost(e_traj, u)                                                                     # 現在のコスト
            lam = backward(e_traj)                                                                   # 手順3,4: 随伴方程式を逆方向計算
            grad = gradient(u, lam)                                                                  # 手順5: 勾配 ∂H/∂u を計算

            gnorm2 = float(grad @ grad)                                                              # 勾配ノルム Σ||∂H/∂u||²
            if gnorm2 < EL_EPS:                                                                      # 手順6: Σ||∂H/∂u||² < ε なら収束
                break

            # 手順7: u ← clip(u - α ∂H/∂u, -u_lim, u_lim)
            #   固定 α では発散しうるため、コストが減少する α をバックトラッキングで選ぶ。
            #   J は u の2次形式なので、有界プローブ点から厳密最小ステップ α*=||g||²/(gᵀH g) を
            #   推定して初期値にできる（レート罰則も u の2次形式なのでこの曲率推定はそのまま成り立つ）。
            gmax = float(np.max(np.abs(grad)))                                                       # 勾配の最大成分（プローブ幅の基準）
            if gmax < 1e-12:                                                                         # 勾配がほぼ0なら収束
                break
            s = u_lim / gmax                                                                         # 過大ステップを避ける有界プローブ幅（最大成分が u_lim 動く）
            u_probe = u - s * grad                                                                   # 方向 -grad 上のプローブ点
            Js = cost(error_traj(forward(u_probe)), u_probe)                                         # プローブ点でのコスト
            gHg = 2.0 * (Js - J0 + s * gnorm2) / (s * s)                                             # 2次曲率 gᵀH g（J は u の2次形式）
            alpha = gnorm2 / gHg if gHg > 1e-30 else s                                               # 厳密最小ステップ α*=||g||²/(gᵀH g)

            accepted = False                                                                         # コストを減少させる α が見つかったか
            for _ls in range(EL_LS_MAX):                                                             # バックトラッキング
                u_cand = np.clip(u - alpha * grad, -u_lim, u_lim)                                    # FF振幅の上限（トラストリージョン）へ射影
                J_cand = cost(error_traj(forward(u_cand)), u_cand)                                   # 候補入力のコスト
                if J_cand < J0:                                                                      # コストが減少したら採用
                    accepted = True
                    break
                alpha *= 0.5                                                                         # 減少しなければステップ幅を半分にして再試行
            if not accepted:                                                                         # どのステップ幅でも改善しなければ収束
                break
            u = u_cand                                                                               # 入力列を更新
            if J0 - J_cand < 1e-9 * (abs(J0) + 1.0):                                                 # 改善が微小なら収束
                break

        # ---- 最適な u_FF を与えたときの閉ループ軌道を作り直し、内部ADRCが出していた入力を取り出す ----
        xi_traj = forward(u)                                                                         # 最適入力での閉ループ軌道 ξ(0..M)
        u_adrc = xi_traj[:M] @ u_row + u_c                                                           # 内部ADRCが各時刻で出した入力 u_ADRC(0..M-1)（絶対PWM）
        u_adrc[0] = float(u_row0 @ xi_traj[0] + u_c0)                                                # k=0 だけ補正後の式で上書き（理論キック kp·step/ic と一致する）
        self.last_u_adrc = u_adrc                                                                    # 呼び出し側の確認用に保存
        self.last_xi = xi_traj                                                                       # 呼び出し側の確認用に保存

        u_ff_opt = np.zeros(M)                                                                       # ELで最適化したFF入力 u_FF_opt（全時間分）
        u_ff_opt[:N_ff] = u                                                                          # FF入力区間 (0..N_ff-1) に最適化したFF分を格納
        u_opt = (u_adrc - float(u_hold)) + u_ff_opt                                                  # 総最適入力 u = (u_ADRC - u_hold) + u_FF_opt（z形式）

        # ---- 5次多項式フィット（0≤t<T, 端点0, 極値2個）。近似対象は総入力ではなくFF分 ----
        t_ff = self.t_eval[:N_ff]                                                                    # FF入力を与える時間だけ取り出す
        u_opt_ff = u_ff_opt[:N_ff]                                                                   # FF入力を与える区間だけの u_FF_opt を取り出す
        (a, b, c, d), (t1, t2) = self.fit_ff_poly(t_ff, u_opt_ff, u_lim)                             # 5次関数パラメータと極値時刻を取得
        e = self.coeff_e(a, b, c, d)                                                                 # f(T)=0 から決まる5次関数パラメータ e
        y1 = float(self.poly(t1, a, b, c, d))                                                        # t1における5次関数値 y1（正の極大値）
        y2 = float(self.poly(t2, a, b, c, d))                                                        # t2における5次関数値 y2（負の極小値）

        u_pred_full = np.zeros(M)                                                                    # シミュレーション時間全体の5次関数FF入力
        u_pred_full[:N_ff] = self.poly(t_ff, a, b, c, d)                                             # FF入力区間だけ5次関数の値を格納

        info = {                                                                                     # 呼び出し側で記録する補助情報
            'k_s': int(k_s),                                                                          # Q_k の切替インデックス（目標軌道の整定時刻）
            'cl_radius': float(self.last_cl_radius),                                                  # 閉ループのスペクトル半径
            'fit_mode': int(self.last_fit_mode),                                                      # 5次フィットの経路（0=L²射影, 1=退避, -1=失敗, -3=f≡0）
            'u_max': float(u_lim),                                                                    # このとき使ったFF振幅の上限
            'u_adrc': u_adrc,                                                                         # 内部ADRCが出した入力（絶対PWM）
            'xi': xi_traj,                                                                            # 閉ループの拡大状態軌道（ζ3 の照合に使う）
        }
        return [a, b, c, d, e], (t1, y1, t2, y2), u_pred_full, y_tgt, u_opt, u_ff_opt, info           # 5次関数パラメータ・極値・5次FF入力・目標モデル応答・総最適入力・ELのFF入力・補助情報

    # 制御性能を評価する関数（重みに依存しない指標）
    def compute_J(self, y_tgt, y_sys):                                                               # 引数(目標モデルの応答, 比較する応答)
        """評価関数 J_eval = Σ(y_tgt - y_sys)²（目標軌道との二乗誤差）

        これは Q_k・R・R_du に依存しない指標である。最適化のコスト J は Q_k の関数であり、
        Q_k は毎ループ再同定される目標モデルから決まる k_s に依存するため、ループ間・重み間で
        比較できない。内側ループの収束判定とトラストリージョンの ρ_tr にはこちらを使う。
        """
        return float(np.sum((np.asarray(y_tgt) - np.asarray(y_sys)) ** 2))                           # 二乗和誤差を返す


