    # ビューア用スナップショットを書き出す関数
    def save_snapshot(self, snap_dof, total_J):                                                     # 引数(自由度ごとのビューア用データ, 今回の評価関数値の合計)
        """最新の波形と、内側ループごとのパラメータ履歴を1つの .npz にまとめて保存する。

        別プロセスのビューア（test_code8.py）がこのファイルの更新時刻を監視し、更新されていれば
        読み直して再描画する。一時ファイルへ書いてから os.replace でアトミックに差し替えるため、
        ビューアが書き込み途中のファイルを掴むことはない。
        保存に失敗しても最適化は続行する（ビューアは実験の必須要素ではないため）。
        """
        if not snap_dof:                                                                            # データが無ければ何もしない
            return

        # 自由度方向に積んだ配列を作る関数（24行の2次元配列になる）
        def stack(key):
            return np.array([np.asarray(d[key], dtype=np.float32) for d in snap_dof], dtype=np.float32)

        # 内側ループごとのスカラー値を履歴へ追加する（横軸 Inner loop = 0 が初回同定）
        self.param_history.append({
            'tgt': stack('tgt_params_used'), 'sys': stack('sys_params_used'),                       # そのループのFFを計算するのに使ったモデル
            'ext': stack('extrema'),                                                                # そのループで印加したFFの極値
            'J': stack('J'),                                                                        # DOF別評価関数値（実測と目標モデルの差）
            'adrc_res': stack('adrc_res'), 'cl_radius': stack('cl_radius'),                         # 内部ADRCと実測PWMの残差・閉ループのスペクトル半径
            'r3_rms': stack('r3_rms'), 'u_max': stack('u_max'), 'rho_tr': stack('rho_tr'),          # モデル誤差指標・FF振幅上限・トラストリージョン比
            'total_J': float(total_J), 'best_J': float(self.min_J_sum),                             # 全DOF合計J・ベストJ
        })
        hist = self.param_history                                                                   # 履歴の参照

        snap = {
            # --- 現在の状態 ---
            'session': self.session_id,                                                             # この実行の識別ID（ビューアが前回の実行と区別するために使う）
            'outer': self.current_outer + 1, 'max_outer': self.max_outer_iter,                      # 外側ループ番号
            'inner': self.current_inner, 'max_inner': self.max_inner_iter,                          # 内側ループ番号
            'total_J': float(total_J), 'best_J': float(self.min_J_sum),                             # 今回のJ・ベストJ
            'T': float(self.T), 'dt': float(self.dt), 'time': time.strftime('%Y-%m-%d %H:%M:%S'),   # FF制御時間・刻み・更新時刻
            'opt_dof': np.array(OPT_DOF_IDS, dtype=np.int32),                                       # 最適化対象の自由度番号（1始まり）
            'threshold_J': float(self.threshold_J),                                                 # 内側ループの収束判定閾値
            # --- 最新の波形（24自由度 × 時系列） ---
            't': self.dt * np.arange(len(snap_dof[0]['y_data']), dtype=np.float32),                 # 時間軸
            'y_data': stack('y_data'), 'y_sys': stack('y_sys'), 'y_tgt': stack('y_tgt'),            # 実測・システムモデル・目標モデル
            'y_gap': np.array([np.asarray(d['y_gap'], dtype=bool) for d in snap_dof], dtype=bool),  # 実測が無く補間で作った区間
            'u_ff_opt_used': stack('u_ff_opt_used'), 'u_ff_applied': stack('u_ff_applied'),         # ELのFF入力 u_FF_opt・印加した5次関数FF
            'u_opt_used': stack('u_opt_used'),                                                      # ELの総最適入力（内部ADRC分＋u_FF_opt）
            'u_adrc_meas': stack('u_adrc_meas'), 'u_adrc_cl': stack('u_adrc_cl'),                   # 実測ADRC出力・内部複製が出したADRC出力
            'z3_meas': stack('z3_meas'), 'zeta3_sim': stack('zeta3_sim'),                           # 実測z3・内部複製が予測したζ3（一致すべき量）
            # --- 最新のパラメータ（24自由度分） ---
            'tgt_params_id': stack('tgt_params_id'), 'sys_params_id': stack('sys_params_id'),       # 今回同定したモデル
            'tgt_params_used': stack('tgt_params_used'), 'sys_params_used': stack('sys_params_used'),  # 今回のFFを作るのに使ったモデル
            'ff': stack('ff'), 'extrema': stack('extrema'),                                         # 印加したFFのパラメータ・極値
            'J': stack('J'), 'Pi': stack('Pi'), 'Pf': stack('Pf'),                                  # 評価関数値・初期位置・目標位置
            'pot_idx': np.array([d['pot_idx'] for d in snap_dof], dtype=np.int32),                  # 26要素配列でのインデックス
            'opt': stack('opt'),                                                                    # 最適化対象の自由度か（1/0）
            'fit_res': stack('fit_res'),                                                            # 5次近似の残差
            'fit_mode': np.array([d['fit_mode'] for d in snap_dof], dtype=np.int32),                # 5次フィットの経路
            'id_res_sys': stack('id_res_sys'),                                                      # システムモデル同定の残差
            'adrc_res': stack('adrc_res'), 'adrc_res_open': stack('adrc_res_open'),                 # 内部ADRCと実測PWMの残差（仕上げ後・仕上げ前）
            'adrc_kick': stack('adrc_kick'), 'adrc_delay': stack('adrc_delay'),                     # 比例キック 実測/理論・通信遅れ[サンプル]
            'cl_radius': stack('cl_radius'), 'cl_ok': stack('cl_ok'),                               # 閉ループのスペクトル半径・仕上げを採用したか
            'r3_rms': stack('r3_rms'), 'k_s': stack('k_s'),                                         # モデル誤差指標 r3 の rms・Q_k の切替インデックス
            'u_max': stack('u_max'), 'rho_tr': stack('rho_tr'), 'accept': stack('accept'),          # FF振幅上限・トラストリージョン比・FF更新を採用したか
            # --- 履歴（内側ループ × 24自由度） ---
            'hist_tgt': np.array([r['tgt'] for r in hist]), 'hist_sys': np.array([r['sys'] for r in hist]),  # 使用したモデルの推移
            'hist_ext': np.array([r['ext'] for r in hist]),                                         # 印加したFFの極値の推移
            'hist_J': np.array([r['J'] for r in hist]),                                             # 評価関数値の推移
            'hist_adrc_res': np.array([r['adrc_res'] for r in hist]),                               # 内部ADRCと実測PWMの残差の推移
            'hist_cl_radius': np.array([r['cl_radius'] for r in hist]),                             # 閉ループのスペクトル半径の推移
            'hist_r3_rms': np.array([r['r3_rms'] for r in hist]),                                   # モデル誤差指標 r3 の推移
            'hist_u_max': np.array([r['u_max'] for r in hist]),                                     # FF振幅上限の推移
            'hist_rho_tr': np.array([r['rho_tr'] for r in hist]),                                   # トラストリージョン比の推移
            'hist_total_J': np.array([r['total_J'] for r in hist], dtype=np.float32),               # 全DOF合計Jの推移
            'hist_best_J': np.array([r['best_J'] for r in hist], dtype=np.float32),                 # ベストJの推移
        }

        try:
            tmp_path = SNAPSHOT_PATH + ".tmp"                                                       # 一時ファイル名
            with open(tmp_path, 'wb') as fp:                                                        # 拡張子を勝手に付けられないようファイルオブジェクトで渡す
                np.savez(fp, **snap)
            os.replace(tmp_path, SNAPSHOT_PATH)                                                     # アトミックに差し替える
        except Exception as exc:
            self.get_logger().warn(f"スナップショット保存失敗: {exc}")                                 # 失敗しても最適化は続行する

    # 外側ループが終了した時点で得られた最良のFFパラメータを一覧表示する関数
    def _print_best_params(self):
        """外側ループ完了時に最良パラメータ a,b,c,d,e と t1,y1,t2,y2 を表示する（対象自由度のみ）"""
        self.get_logger().info("")
        self.get_logger().info("=" * 100)
        self.get_logger().info(f"  外側ループ {self.current_outer + 1} 最良結果 (ベストJ = {self.min_J_sum:.2f})")
        self.get_logger().info("=" * 100)
        self.get_logger().info(
            f"  {'DOF':>4s} | {'a':>12s}  {'b':>12s}  {'c':>12s}  {'d':>12s}  {'e':>12s}"
            f"  | {'t1':>6s}  {'y1':>8s}  {'t2':>6s}  {'y2':>8s}"
        )
        self.get_logger().info("  " + "-" * 96)
        for dof_idx in OPT_DOF_IDX:                                                                 # 最適化対象の自由度だけ表示する
            a, b, c, d, e = self.best_ff_matrix[dof_idx]                                            # パラメータを取得
            t1, y1, t2, y2 = self.best_extrema[dof_idx]                                             # 極値取得
            self.get_logger().info(
                f"  {dof_idx + 1:4d} | {a:>12.4e}  {b:>12.4e}  {c:>12.4e}  {d:>12.4e}  {e:>12.4e}"
                f"  | {t1:6.3f}  {y1:8.2f}  {t2:6.3f}  {y2:8.2f}"
            )
        self.get_logger().info("=" * 100)
        self.get_logger().info("")

    # 外側ループで最終的に得られた最良結果をCSVへ保存する関数
    def save_optimal_results_to_csv(self):
        """24自由度分の Init, Target, T, t1, y1, t2, y2 を1行に横並びして追記する（現行仕様どおり）"""
        dof_map = self.build_dof_map()                                                              # 26要素→24自由度対応表の作成
        row_data = {}                                                                               # 空の辞書作成
        for dof_idx in range(N_DOF_ALL):                                                            # 24自由度ループ
            Pi = self.initial_pot[dof_map[dof_idx]]                                                 # 初期位置取得
            Pf = self.target_pot[dof_map[dof_idx]]                                                  # 目標位置取得
            t1, y1, t2, y2 = self.best_extrema[dof_idx]                                             # 極値取得
            row_data[f'Init_{dof_idx + 1}'] = Pi                                                    # 初期位置
            row_data[f'Target_{dof_idx + 1}'] = Pf                                                  # 目標位置
            row_data[f'T_{dof_idx + 1}'] = self.T                                                   # FF制御入力時間
            row_data[f't1_{dof_idx + 1}'] = t1                                                      # 極大時刻
            row_data[f'y1_{dof_idx + 1}'] = y1                                                      # 極大値
            row_data[f't2_{dof_idx + 1}'] = t2                                                      # 極小時刻
            row_data[f'y2_{dof_idx + 1}'] = y2                                                      # 極小値

        df = pd.DataFrame([row_data])                                                               # データを横並びにする
        header = not os.path.exists(self.csv_path)                                                  # 既存ファイルがあるか判定
        df.to_csv(self.csv_path, mode='a', header=header, index=False)                              # csvへ保存
        self.get_logger().info(f"CSV保存完了: {self.csv_path}")

    # デバッグExcelへ、この外側ループぶんのシートを2枚追加する関数
    def save_debug_to_excel(self, snap_dof, total_J):                                               # 引数(自由度ごとの記録用データ, 今回の評価関数値の合計)
        """内側ループ終了時（＝外側ループ終了時）の結果を1つのブックへ2シート追加する。

        シート "Iter_N"（1枚目）
          ・全24自由度の Time-POT グラフ（実測 / システムモデル / 目標モデル）を画像で貼る
          ・最適化対象自由度だけ、そのときの評価関数J をセルへ数値で書く
        シート "Input_Iter_N"（2枚目）
          ・最適化対象自由度の Time-PWM グラフ（u_FF_opt / u_opt / 送信した5次関数FF）を画像で貼る
          ・そのとき実際に与えていたFFパラメータ a,b,c,d,e と極値 t1,y1,t2,y2 をセルへ数値で書く

        貼るのは「ベスト値」ではなく「内側ループ終了時に実際に与えていた値」である
        （snap_dof は画像・数値ともにそのループで印加したFFとそのときの実測から作られている）。
        ブックはメモリ上に保持し、ファイルへの書き出しは全試行終了時（FINISHED）に1回だけ行う。
        openpyxl は貼った画像のファイルを保存時まで読むので、一時PNGはここでは削除しない。
        """
        if not snap_dof:                                                                            # 記録が無ければ何もしない
            return
        n_outer = self.current_outer + 1                                                            # この外側ループの番号（1始まり）
        n_inner = self.current_inner                                                                # 収束した時点の内側ループ回数
        t = self.dt * np.arange(len(np.asarray(snap_dof[0]['y_data'])))                             # 時間軸 [s]

        # ---- 1枚目: 全自由度の Time-POT グラフ ＋ 最適化対象自由度の評価関数J ----
        ws = self.debug_wb.create_sheet(title=f"Iter_{n_outer}")                                    # シート作成
        ws.cell(row=1, column=1, value="DOF")                                                       # A列の見出し
        ws.cell(row=1, column=2, value="J (inner loop end)")                                        # B列の見出し
        ws.cell(row=1, column=3, value="optimized")                                                 # C列の見出し（最適化対象かどうか）
        for dof_idx, d in enumerate(snap_dof):                                                      # 24自由度ループ
            is_opt = float(d['opt']) > 0.5                                                          # この自由度が最適化対象か
            ws.cell(row=dof_idx + 2, column=1, value=dof_idx + 1)                                   # A列へDOF番号を格納
            if is_opt:                                                                              # 最適化対象自由度だけJを数値で残す
                ws.cell(row=dof_idx + 2, column=2, value=float(d['J']))                             # B列へ評価関数Jを格納
            ws.cell(row=dof_idx + 2, column=3, value="yes" if is_opt else "no")                     # C列へ最適化対象かどうかを格納
        ws.cell(row=N_DOF_ALL + 3, column=1, value="total J (opt DOF)")                             # 合計Jの見出し
        ws.cell(row=N_DOF_ALL + 3, column=2, value=float(total_J))                                  # 最適化対象自由度の合計J
        ws.cell(row=N_DOF_ALL + 4, column=1, value="inner loops")                                   # 内側ループ回数の見出し
        ws.cell(row=N_DOF_ALL + 4, column=2, value=int(n_inner))                                    # 収束までに回した内側ループ回数

        for dof_idx, d in enumerate(snap_dof):                                                      # 24自由度ぶんの Time-POT グラフを貼る
            gap = np.asarray(d['y_gap'], dtype=bool)                                                # 実測が無く補間の直線になっている区間
            y_show = np.where(gap, np.nan, np.asarray(d['y_data'], dtype=float))                    # 補間の直線は実測として描かない
            plt.figure(figsize=EXCEL_FIGSIZE, dpi=EXCEL_DPI)                                        # 新しいグラフを作成
            plt.plot(t, y_show, 'k-', lw=1.2, label='Measured')                                     # 実測POT値
            plt.plot(t, d['y_sys'], 'b--', lw=1.0, label='System model')                            # 同定したシステムモデルの応答
            plt.plot(t, d['y_tgt'], 'r:', lw=1.4, label='Target model')                             # 同定した目標モデルの応答
            plt.axhline(float(d['Pf']), color='g', lw=0.8, ls='-.')                                 # 目標位置
            plt.axvline(float(self.T), color='0.5', lw=0.8, ls=':')                                 # FF入力の終了時刻 T
            j_txt = f"J = {float(d['J']):.2f}" if float(d['opt']) > 0.5 else "not optimized"        # タイトルへ出す評価値
            plt.title(f"DOF {dof_idx + 1} Time-POT  ({j_txt})")                                     # グラフのタイトル
            plt.xlabel("Time [s]"); plt.ylabel("POT [count]")                                       # 軸ラベル
            plt.legend(fontsize=8); plt.grid(alpha=0.3)                                             # 凡例とグリッド
            img_path = os.path.join(EXCEL_IMG_DIR, f"el7_pot_iter{n_outer}_dof{dof_idx + 1}.png")   # 画像ファイル名を作成
            plt.savefig(img_path, bbox_inches='tight')                                              # PNG画像として保存
            plt.close()                                                                             # グラフを閉じる
            col = "E" if dof_idx % 2 == 0 else "N"                                                  # 偶数自由度は左に、奇数自由度は右に配置
            ws.add_image(OpenpyxlImage(img_path), f"{col}{2 + (dof_idx // 2) * 22}")                # 画像を貼り付ける

        # ---- 2枚目: 最適化対象自由度の Time-PWM グラフ ＋ FFパラメータと極値 ----
        ws_in = self.debug_wb.create_sheet(title=f"Input_Iter_{n_outer}")                           # シート作成
        for col_idx, h in enumerate(["DOF", "a", "b", "c", "d", "e", "t1", "y1", "t2", "y2"], start=1):
            ws_in.cell(row=1, column=col_idx, value=h)                                              # 見出し行を作成
        row = 2                                                                                     # 書き込む行（最適化対象自由度だけ詰めて並べる）
        for dof_idx, d in enumerate(snap_dof):                                                      # 24自由度ループ
            if float(d['opt']) <= 0.5:                                                              # 最適化対象外はFFが常に0なので載せない
                continue
            a, b, c, dd, e = [float(v) for v in d['ff']]                                            # 実際に与えていたFFパラメータ
            t1, y1, t2, y2 = [float(v) for v in d['extrema']]                                       # そのときの極値
            for col_idx, val in enumerate([dof_idx + 1, a, b, c, dd, e, t1, y1, t2, y2], start=1):
                ws_in.cell(row=row, column=col_idx, value=val)                                      # 1行にまとめて書き込む

            plt.figure(figsize=EXCEL_FIGSIZE, dpi=EXCEL_DPI)                                        # 新しいグラフを作成
            plt.plot(t, d['u_ff_opt_used'], 'c-', lw=1.0, label='u_FF_opt (EL)')                    # ELが出した最適FF入力
            plt.plot(t, d['u_opt_used'], color='0.6', lw=0.8, ls='--', label='u_opt = u_ADRC + u_FF')  # 総最適入力
            plt.plot(t, d['u_ff_applied'], 'r-', lw=1.4, label='u_FF (5th-order, sent)')            # 実機へ送った5次関数FF
            plt.plot([t1, t2], [y1, y2], 'ro', ms=5)                                                # 極値マーカー
            plt.axhline(0.0, color='k', lw=0.6)                                                     # 0線
            plt.axvline(float(self.T), color='0.5', lw=0.8, ls=':')                                 # FF入力の終了時刻 T
            plt.xlim(0, min(float(self.T) * 1.6, float(t[-1])))                                     # FF区間まわりを拡大して見る
            plt.title(f"DOF {dof_idx + 1} Time-PWM  "
                      f"(t1={t1:.3f}, y1={y1:+.2f} / t2={t2:.3f}, y2={y2:+.2f})")                   # グラフのタイトル
            plt.xlabel("Time [s]"); plt.ylabel("PWM")                                               # 軸ラベル
            plt.legend(fontsize=8); plt.grid(alpha=0.3)                                             # 凡例とグリッド
            img_path = os.path.join(EXCEL_IMG_DIR, f"el7_pwm_iter{n_outer}_dof{dof_idx + 1}.png")   # 画像ファイル名を作成
            plt.savefig(img_path, bbox_inches='tight')                                              # PNG画像として保存
            plt.close()                                                                             # グラフを閉じる
            ws_in.add_image(OpenpyxlImage(img_path), f"L{2 + (row - 2) * 22}")                      # 画像を貼り付ける（行ごとに下へずらす）
            row += 1                                                                                # 次の最適化対象自由度へ

        self.get_logger().info(f"デバッグExcelへシートを追加: Iter_{n_outer} / Input_Iter_{n_outer}")


