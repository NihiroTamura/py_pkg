    # ROS2のタイマーのコールバック関数
    def sequencer_loop(self):
        now = self.get_clock().now()                                                                # 現在の時刻を取得
        elapsed = (now - self.state_start_time).nanoseconds / 1e9                                   # 経過時間を計算

        # 初期姿勢へ戻す状態
        if self.state == "INIT_ROBOT":
            self.get_logger().info(                                                                 # ログ出力
                f"=== 最適制御 外側ループ {self.current_outer + 1} / {self.max_outer_iter} "
                f"(内側ループ {self.current_inner + 1}/{self.max_inner_iter}) ==="
            )
            self.publish_target_positions(self.initial_pot)                                         # 初期姿勢を送信
            self.state = "WAIT_INITIAL_STABILIZE"                                                   # 状態変更
            self.state_start_time = now                                                             # 現在時刻を取得

        # 初期姿勢への収束を待っている状態
        elif self.state == "WAIT_INITIAL_STABILIZE":
            if elapsed >= self.initial_stabilize_time:                                              # 待ち時間が終了したか判定
                # 同定入力の基準となる保持PWMと ζ3(0⁻) は、FF・目標値を送る前（静止中）に取る
                self.hold_pwm_24 = self.capture_hold(self.pwm_hold_window)                          # 目標値切替直前の保持PWMを24自由度分取得
                self.hold_z3_24 = self.capture_hold(self.z3_hold_window) if self.z3_seen else None  # 目標値切替直前のz3を24自由度分取得
                if not self.z3_seen:                                                                # z3トピックが1度も届いていない場合
                    self.get_logger().warn(
                        f"{TOPIC_Z3.format('{i}')} を受信していません。ζ3(0) を推定値で代用せず、"
                        f"該当自由度のFF更新を見送ります"
                    )
                self.publish_all_ff_parameters()                                                    # FFパラメータを送信
                time.sleep(0.1)                                                                     # 0.1秒待機（Teensyは目標値受信をFFのt=0とするため順序と間隔を守る）
                self.publish_target_positions(self.target_pot)                                      # 目標値送信
                # バッファは clear() ではなく新しい辞書へ差し替える。購読コールバックは別スレッドで
                # 動いているため、clear() だと「消した直後に古いデータが1点入る」ことがある。
                self.buffer_pot = {f'board{i}': [] for i in range(1, 6)}                            # POTデータバッファを初期化
                self.buffer_pwm = {f'board{i}': [] for i in range(1, 6)}                            # PWMデータバッファを初期化
                self.buffer_z3 = {f'board{i}': [] for i in range(1, 6)}                             # z3データバッファを初期化
                # 収集開始時刻は、FF・目標値の送信（極値計算とログ出力を含む）が終わった後の
                # 時刻に取り直す。タイマー先頭の now を使うと、送信にかかった時間だけ収集時間が短くなる。
                self.collect_start_time = self.get_clock().now()                                    # 受信時刻の基準となるデータ収集開始時刻
                self.state = "COLLECTING"                                                           # 状態変更
                self.state_start_time = self.collect_start_time                                     # 収集開始時刻を状態開始時刻にも使う

        # ロボットの実測データを収集している状態
        elif self.state == "COLLECTING":
            spans = self.collected_spans()                                                          # 各boardが何秒分のデータを受信できたかを取得
            min_span = min(spans.values())                                                          # 最も受信が遅れているboardの時間長
            timeout = elapsed >= self.data_collection_time + COLLECT_EXTRA_WAIT                     # 追加待機の上限を超えたか判定

            # 経過時間だけでなく「全boardが指定時間分のデータを受信できたか」も条件にする。
            # 配信の遅れや取りこぼしで短いデータのまま次へ進んでしまうのを防ぐ。
            if (elapsed >= self.data_collection_time and min_span >= self.data_collection_time - self.dt) or timeout:
                if timeout and min_span < self.data_collection_time - self.dt:                      # 指定時間分そろわないまま打ち切った場合
                    short = {k: v for k, v in spans.items() if v < self.data_collection_time - self.dt}  # 不足しているboardを抽出
                    self.get_logger().warn(
                        f"データ収集が {self.data_collection_time:.1f}s 分そろいませんでした（"
                        + ", ".join(f"{k}={v:.2f}s" for k, v in sorted(short.items())) + "）"
                    )
                else:                                                                               # 指定時間分そろった場合
                    n_pot = [len(self.buffer_pot[f'board{i}']) for i in range(1, 6)]                # boardごとのPOT受信点数
                    n_pwm = [len(self.buffer_pwm[f'board{i}']) for i in range(1, 6)]                # boardごとのPWM受信点数
                    n_z3 = [len(self.buffer_z3[f'board{i}']) for i in range(1, 6)]                  # boardごとのz3受信点数
                    self.get_logger().info(
                        f"データ収集完了: {elapsed:.2f}s 経過 / 全board {min_span:.2f}s 分を受信 "
                        f"(受信点数 POT={n_pot}, PWM={n_pwm}, z3={n_z3} "
                        f"→ {eval_horizon(SIM_TIME, self.dt)}点へ補間)"
                    )
                self.state = "PROCESSING"                                                           # 状態変更
                self.publish_target_positions(self.initial_pot)                                     # 初期姿勢を送信
                threading.Thread(target=self.dispatch_optimization_pipeline, daemon=True).start()   # 最適化パイプラインを別スレッドで実行する

        # プログラムの最終状態
        elif self.state == "FINISHED":
            self.get_logger().info("=== 最終安定化: home_pot を送信します ===")                       # ログ出力
            self.publish_target_positions(self.home_pot)                                            # オリジナルの初期姿勢を送信
            if DEBUG_EXCEL:                                                                         # デバッグExcelをファイルへ書き出す
                try:
                    if self.default_sheet in self.debug_wb.worksheets and len(self.debug_wb.worksheets) > 1:  # 既定の空シートが残っていて他にシートがある場合
                        self.debug_wb.remove(self.default_sheet)                                    # 空シートを削除する
                    self.debug_wb.save(self.excel_path)                                             # ブックを保存する
                    self.get_logger().info(f"デバッグExcel保存: {self.excel_path}")
                except Exception as exc:                                                            # 保存に失敗しても終了処理は続ける
                    self.get_logger().error(f"デバッグExcel保存失敗: {exc}")
            self.get_logger().info("すべての実験試行が正常終了しました。")
            self.control_timer.cancel()                                                             # タイマー停止
            self.shutdown_event.set()                                                               # main()の実行ループへ終了を伝える

    # ------------------------------------------------------------------
    # 最適化パイプライン（実測データ → 同定 → EL最適制御 → 5次近似 → FF更新）
    # ------------------------------------------------------------------

    # 実測データから次回のFF入力を計算する関数（スレッド関数）
    def dispatch_optimization_pipeline(self):
        try:
            dof_map = self.build_dof_map()                                                          # 24自由度 → 26要素配列インデックスの対応表
            solver = MathematicalSolver(self.T, self.dt)                                            # 数学ソルバーの生成
            M = solver.M                                                                            # 評価ホライズンのサンプル数
            t_grid = solver.t_eval                                                                  # シミュレーションの時間軸（0秒～, M点）

            # Boardごとの時系列を、受信時刻を使って24自由度分の時間軸へ揃える関数
            #   1サンプル=CTRL_DT秒と決め打ちせず実際の受信時刻で補間するため、配信の遅れや
            #   取りこぼしがあっても必ず [0, SIM_TIME] 全体をカバーした M 点のデータになる。
            #   ただし受信が途切れた区間は補間が直線で埋めてしまうので、その位置も一緒に返す。
            def build_24_dof(buffer, label, grid, quiet=False):                                     # 引数(受信バッファ, ログ表示名, 揃える時間軸, 警告を出さないか)
                out, gaps = [], []                                                                  # 24自由度分の値と欠測マスクの空リスト
                for b_id in range(1, 6):                                                            # board1からboard5の順に処理
                    samples = list(buffer[f'board{b_id}'])                                          # 各boardに対応する受信データ（受信時刻, 値）
                    n_dof = 3 if b_id in [4, 5] else 6                                              # board4と5は3自由度、それ以外は6自由度
                    if not samples:                                                                 # 1点も受信できなかった場合
                        out.extend([None] * n_dof); gaps.extend([None] * n_dof)                     # 未受信として格納
                        if not quiet:
                            self.get_logger().warn(f"{label}-board{b_id}: 1点も受信できませんでした")
                        continue
                    stamps = np.array([s[0] for s in samples], dtype=float)                         # 受信時刻の配列
                    arr = np.array([s[1] for s in samples], dtype=float)                            # 受信値の配列
                    gap = self.gap_mask(stamps, grid)                                               # 欠測マスク（受信時刻はboard内の全自由度で共通）
                    if not quiet:
                        self.report_gaps(label, b_id, stamps, gap, grid)                            # 欠測があれば警告ログを出す
                    for j in range(n_dof):                                                          # そのboardの自由度の順に処理
                        out.append(self.resample_by_time(stamps, arr[:, j], grid))                  # 受信時刻で補間して格納
                        gaps.append(gap)
                return out, gaps

            # 1段目: まず素の時間軸で揃えて、目標値がロボットへ届くまでの通信遅れ δ を測る
            #   シミュレーションの t=0 は「Pythonが目標値をpublishし終えた瞬間」だが、ロボットが
            #   実際に目標値を受け取ってFFタイマを開始するのは DDS→micro-ROS→シリアル の分だけ
            #   後になる。この遅れはどこにも計測されていないため、実測PWMの比例キック
            #       Δu_pwm = kp·step/input_coef
            #   が立ち上がるサンプル番号から直接読み取る（詳細は detect_adrc_kick 参照）。
            pwm_raw, _ = build_24_dof(self.buffer_pwm, "PWM", t_grid, quiet=True)                   # 遅れ推定用のPWM（警告は2段目で出す）
            kick_ratio = [float('nan')] * N_DOF_ALL                                                 # 自由度ごとの実測キック/理論キック
            kick_delay = [float('nan')] * N_DOF_ALL                                                 # 自由度ごとの通信遅れ[サンプル]
            for d_i in range(N_DOF_ALL):                                                            # 24自由度分のキック検査
                if not OPT_DOF_MASK[d_i]:                                                           # 最適化対象外の自由度は判定しない（目標値がほぼ動かないため）
                    continue
                u_d = pwm_raw[d_i]                                                                  # その自由度の実測PWM
                hold_d = self.hold_pwm_24[d_i] if self.hold_pwm_24 is not None else None            # 目標値切替直前の保持PWM
                if u_d is None or hold_d is None:                                                   # PWMか保持PWMが取れなかった場合
                    continue                                                                        # 判定不能のまま次の自由度へ
                step_d = self.target_pot[dof_map[d_i]] - self.initial_pot[dof_map[d_i]]             # 目標変位 Pf - Pi
                kick_delay[d_i], kick_ratio[d_i] = solver.detect_adrc_kick(                         # 比例キックから遅れとゲイン整合を測る
                    u_d, hold_d, ADRC_KP[d_i], ADRC_INPUT_COEF[d_i], step_d)

            det = [d for d in kick_delay if np.isfinite(d)]                                         # 判定できた自由度の遅れ
            lag = int(round(float(np.median(det)))) if det else 0                                   # 全体の遅れは中央値を採用（通信路の性質なのでboard間で共通のはず）
            if det:                                                                                 # 1つでも判定できた場合
                ratios = [r for r in kick_ratio if np.isfinite(r)]                                  # 判定できた自由度のキック比
                self.get_logger().info(
                    f"通信遅れ δ = {lag} サンプル ({lag * self.dt * 1000:.0f} ms)  "
                    f"[判定できた自由度 {len(det)}/{len(OPT_DOF_IDX)}]  "
                    f"比例キック 実測/理論 = {np.mean(ratios):.3f} (平均)"
                )
                if lag > 5:                                                                         # 遅れが大きい場合
                    self.get_logger().warn(f"目標値がロボットへ届くまで {lag} サンプル遅れています。通信経路を確認してください")
            else:                                                                                   # 1つも判定できなかった場合
                self.get_logger().info("比例キックを判定できる自由度がありません。通信遅れ補正なしで進みます")

            # 2段目: 実測を δ ぶん前詰めして、t=0 が本当の目標値切替時刻になるよう揃え直す
            t_shift = t_grid + lag * self.dt                                                        # 前詰めした時間軸
            data_24_dof, gap_24_dof = build_24_dof(self.buffer_pot, "POT", t_shift)                 # 実測POT値を24自由度分へ変換
            pwm_24_dof, _ = build_24_dof(self.buffer_pwm, "PWM", t_shift)                           # 実制御入力（PWM）を24自由度分へ変換
            z3_24_dof, _ = build_24_dof(self.buffer_z3, "z3", t_shift, quiet=True)                  # ESO外乱推定値 z3 を24自由度分へ変換

            J_sum = 0.0                                                                             # 最適化対象自由度の評価関数Jの合計
            snap_dof = []                                                                           # ビューア用データ（自由度ごと）の空リスト
            ff_used_this_iteration = [row[:] for row in self.current_ff_matrix]                     # 今回ロボットへ送信したFF（更新前）を保存
            used_extrema_list = [solver.calc_extrema_from_ff(ff) for ff in ff_used_this_iteration]  # そのFFの極値を保存

            for dof_idx in range(N_DOF_ALL):                                                        # 24自由度分のループ
                is_opt = bool(OPT_DOF_MASK[dof_idx])                                                # この自由度が最適化対象か
                Pi = self.initial_pot[dof_map[dof_idx]]                                             # 現在のDOFの初期位置
                Pf = self.target_pot[dof_map[dof_idx]]                                              # 現在のDOFの目標位置
                y0 = Pi - Pf                                                                        # 初期偏差（誤差系の初期値）
                step = Pf - Pi                                                                      # 目標変位（z形式の最終値）
                raw_y = data_24_dof[dof_idx]                                                        # M点に揃え済みの実測データ
                y_gap = gap_24_dof[dof_idx]                                                         # 実測が無く補間の直線になっている区間

                if raw_y is None:                                                                   # POT値を1点も受信できなかった場合
                    if is_opt:                                                                      # 最適化対象なら同定できないので異常として扱う
                        raise RuntimeError(f"DOF {dof_idx + 1:02d}: POT値を1点も受信できませんでした")
                    raw_y = np.full(M, np.nan)                                                      # 対象外なら表示用にNaNで埋める
                    y_gap = np.ones(M, dtype=bool)

                # 目標変位が小さすぎる自由度は、入力も応答もほぼゼロで同定が意味を持たない。
                #   b0 の符号も zeta も決まらず探索境界に張り付くため、自動的に対象から外す。
                if is_opt and abs(step) < STEP_MIN:                                                 # 目標変位が STEP_MIN 未満の場合
                    self.get_logger().warn(
                        f"DOF {dof_idx + 1:02d}: 目標変位 |Pf-Pi| = {abs(step):.1f} < {STEP_MIN} カウント のため"
                        f"最適化対象から外します（同定が成立しないため）"
                    )
                    is_opt = False                                                                  # 対象外として扱う

                # 最適化対象外の自由度は、実測POT値だけを記録して次の自由度へ進む。
                #   目標モデル同定・システムモデル同定・最適入力計算・5次関数フィットはいっさい行わず、
                #   評価関数Jにも算入しない。データ構造（24自由度分の並び）は保ったまま、計算して
                #   いない項目をNaNで埋めるので、ビューア側は表示枠を維持したまま実測POT値だけを描ける。
                if not is_opt:
                    snap_dof.append(self.make_snap_entry(dof_idx, dof_map, M, raw_y, y_gap, Pi, Pf,
                                                         ff_used_this_iteration[dof_idx],
                                                         used_extrema_list[dof_idx]))                # 未計算項目をNaNで埋めた記録用データ
                    continue

                # 欠測が多いと、水平な直線をそのまま同定してしまい振動しないモデルになる
                if y_gap.mean() > GAP_WARN_RATIO:
                    self.get_logger().warn(
                        f"DOF {dof_idx + 1:02d}: 実測データの {y_gap.mean() * 100:.0f}% が補間です。"
                        f"同定結果（特に zeta・wn）は信用できません"
                    )

                y_shifted = raw_y - Pf                                                              # 目標位置を原点（0）に移動した実測データ（誤差系）
                z_data = raw_y - Pi                                                                 # 初期位置を原点（0）にした実測データ（z形式）

                # ビューア表示用に「今回印加したFFを作るのに使った値」を、同定で上書きされる前に控える
                if self.prev_u_ff_opt[dof_idx] is None:                                             # 初回同定（印加したのは初期励振FF）
                    u_ff_opt_used = np.full(M, np.nan)                                              # 表示なし（NaNはグラフに描かれない）
                    u_opt_used = np.full(M, np.nan)                                                 # 表示なし
                    tgt_used, sys_used = [np.nan, np.nan], [np.nan] * 4                             # 表示なし
                    mode_used = -2                                                                  # 表示なしを示す値
                else:                                                                               # 2回目以降（前回の最適制御結果を印加している）
                    u_ff_opt_used = self.prev_u_ff_opt[dof_idx]                                     # 今回のFFの元になった u_FF_opt
                    u_opt_used = self.prev_u_opt[dof_idx]                                           # そのときの総最適入力（内部ADRC分を含む）
                    tgt_used = list(self.prev_tgt_params[dof_idx])                                  # その u_FF_opt を計算するのに使った目標モデル
                    sys_used = list(self.prev_sys_params[dof_idx])                                  # その u_FF_opt を計算するのに使ったシステムモデル
                    mode_used = self.prev_fit_mode[dof_idx]                                         # そのFFを作ったときの5次フィット経路

                # ---- 1. 目標モデル同定 ----
                tgt_params = solver.fit_target_model(y_shifted, y0, self.prev_tgt_params[dof_idx])  # 目標モデルの同定（前回の結果を初期値に使う）
                self.prev_tgt_params[dof_idx] = list(tgt_params)                                    # 次回同定の初期値として保存
                _, y_tgt = solver.build_target_traj(tgt_params, y0, step)                           # 誤差系の目標出力（Jの計算に使う）

                # ---- 2. 内側ループの評価値 J_eval（重み非依存。実測と目標モデルの差） ----
                J_meas = solver.compute_J(y_tgt, y_shifted)                                         # 今回の実測がどれだけ目標軌道に乗ったか
                J_sum += J_meas                                                                     # 対象自由度の合計へ加算

                # ---- 3. トラストリージョンの更新（FF振幅の上限をモデルの当たり具合で決める） ----
                #   ρ_tr = (実測の改善) / (モデルが予測した改善)
                #   J は Q_k の関数なので使えない。重み非依存の J_eval を使う（compute_J のdocstring参照）。
                rho_tr = float('nan')                                                               # 今回の ρ_tr（判定できなければNaN）
                if self.prev_J_meas[dof_idx] is not None and self.prev_J_pred[dof_idx] is not None:  # 前回の実測値と予測値がそろっている場合
                    den = self.prev_J_meas[dof_idx] - self.prev_J_pred[dof_idx]                     # モデルが予測した改善量
                    num = self.prev_J_meas[dof_idx] - J_meas                                        # 実際に得られた改善量
                    if den > TR_DEN_MIN:                                                            # 予測改善がほぼゼロなら判定しない
                        rho_tr = float(num / den)                                                   # トラストリージョン比
                        if rho_tr > TR_EXPAND_RATIO:                                                # モデルが当たっている
                            self.u_max_24[dof_idx] = min(self.u_max_24[dof_idx] * TR_EXPAND_GAIN, PWM_LIMIT)  # 上限を広げる
                        elif rho_tr < TR_SHRINK_RATIO:                                              # モデルが外れている
                            self.u_max_24[dof_idx] = max(self.u_max_24[dof_idx] * TR_SHRINK_GAIN, U_MAX_MIN)  # 上限を縮める
                            self.get_logger().warn(
                                f"DOF {dof_idx + 1:02d}: 予測より実測が悪い (ρ_tr={rho_tr:.2f})。"
                                f"FF振幅の上限を {self.u_max_24[dof_idx]:.1f} PWM へ縮めます"
                            )

                # ---- 4. システムモデル同定（開ループ → 閉ループ仕上げ） ----
                a, b, c, d, e = self.current_ff_matrix[dof_idx]                                     # 今回印加したFFパラメータ
                u_ff = np.zeros(M)                                                                  # 印加したFF入力の時系列
                u_ff[:solver.N_ff] = solver.poly(t_grid[:solver.N_ff], a, b, c, d)                  # FF入力区間だけ5次関数の値を格納

                u_pwm = pwm_24_dof[dof_idx]                                                         # 時間軸へ揃え済みの実測PWM
                if u_pwm is None:                                                                   # PWMを1点も受信できなかった場合
                    self.get_logger().warn(
                        f"DOF {dof_idx + 1:02d}: PWMを受信できませんでした。FF入力でシステムモデルを同定します。")
                    u_pwm = u_ff.copy()                                                             # 従来どおりFF入力で代用する
                    u_hold = 0.0                                                                    # FF入力は0から始まるので基準値も0
                else:                                                                               # PWMを受信できた場合
                    u_hold = self.hold_pwm_24[dof_idx] if self.hold_pwm_24 is not None else None    # 目標値切替直前の保持PWM（同定入力の基準値）
                    if u_hold is None:                                                              # 保持PWMを取得できなかった場合
                        self.get_logger().warn(
                            f"DOF {dof_idx + 1:02d}: 保持PWMを取得できませんでした。収集開始時のPWMで代用します。")
                        u_hold = float(u_pwm[0])                                                    # 収集開始時のPWMで代用する（精度は落ちる）

                u_ident = u_pwm - u_hold                                                            # 同定に使用する入力（初期姿勢の保持分を除去）
                adrc_params = (ADRC_KP[dof_idx], ADRC_KD[dof_idx],                                  # PDゲイン kp, kd
                               ADRC_INPUT_COEF[dof_idx], ADRC_OBS_POLE[dof_idx])                    # 制御入力係数 input_coef, オブザーバの極 λ₀

                # 実測PWMから実機ADRCが実際に出していた入力を復元する
                #   実機は pub = outputADRC + outputAdd を配信しているので、こちらが送った5次関数FF
                #   u_ff を引けばADRC分だけが残る。FFはESOの入力項に入らないので、この引き算だけで
                #   u_ADRC が厳密に取り出せる。最適制御の内部で計算される u_ADRC はこれと一致すべき量。
                u_adrc_meas = (u_pwm - u_ff) if pwm_24_dof[dof_idx] is not None else np.full(M, np.nan)  # 実測ADRC出力（絶対PWM, δ前詰め済み）

                # 実測 z3（ζ3(0) の初期値と、モデル妥当性の照合に使う）
                z3_meas = z3_24_dof[dof_idx] if z3_24_dof[dof_idx] is not None else np.full(M, np.nan)   # z3の時系列
                z3_init = self.hold_z3_24[dof_idx] if self.hold_z3_24 is not None else None         # ζ3(0) に使う実測 z3(0⁻)

                sys_params = solver.fit_system_model(z_data, u_ident, 0.0, self.prev_sys_params[dof_idx])  # 開ループ同定（z形式, 初期値0）

                # 閉ループ同定の仕上げ（開ループ結果を初期値に、実測POTと実測PWMの両方へ合わせる）
                cl_skip = (pwm_24_dof[dof_idx] is None) or (y_gap.mean() > GAP_WARN_RATIO)          # 仕上げを行えない自由度か判定
                if cl_skip:                                                                         # 実測PWMが無い、または欠測が多い場合
                    cl_ok, adrc_res_open, adrc_res = False, float('nan'), float('nan')              # 仕上げなし。残差も判定不能
                else:                                                                               # 仕上げを行える場合
                    sys_params, cl_ok, adrc_res_open, adrc_res = solver.refine_system_model_closed_loop(
                        sys_params, adrc_params, step, u_hold, z_data, u_adrc_meas, u_ff, z3_init)  # 閉ループで再フィット
                self.prev_sys_params[dof_idx] = list(sys_params)                                    # 仕上げ後の値を次回同定の初期値として保存

                pinned = solver.bound_pinned(sys_params)                                            # 探索境界に張り付いた変数（同定失敗の兆候）
                if pinned:                                                                          # 張り付きがあれば記録として残す
                    self.get_logger().warn(
                        f"DOF {dof_idx + 1:02d}: 同定結果が探索境界に張り付いています ({', '.join(pinned)})。"
                        f"励振が足りない可能性があります"
                    )

                # ---- 5. 同定したモデルの応答（表示・残差評価用） ----
                if cl_ok:                                                                           # 閉ループ同定の仕上げを採用した場合
                    z_sys_sim, u_adrc_cl, _ = solver.simulate_closed_loop(                          # 印加したFFで閉ループを回す（合わせた対象と同じ形で評価する）
                        sys_params, adrc_params, step, u_hold, u_ff, z3_init)
                else:                                                                               # 仕上げできなかった場合
                    a2_s, a1_s, a0_s = solver.system_coeffs(*sys_params[:3])                        # 3次遅れ系の係数へ展開
                    z_sys_sim, _, _ = solver.simulate_forced(t_grid, a2_s, a1_s, a0_s,              # 実測PWMを入力として与えた開ループ応答
                                                             sys_params[3], u_ident, 0.0)
                    u_adrc_cl = np.full(M, np.nan)                                                  # 比較できる内部ADRC出力は無い
                y_sys_sim = z_sys_sim + Pi - Pf                                                     # 表示・残差評価用に誤差系（Pf基準）へ戻す

                # ---- 6. 離散時間オイラー・ラグランジュ最適制御 + 5次多項式フィット ----
                (new_ff, extrema, u_pred_full, _, u_opt,
                 u_ff_opt, info) = solver.calculate_el_ff(tgt_params, sys_params, y0, adrc_params,  # FFパラメータ・極値・5次FF入力・総最適入力・ELのFF入力
                                                          u_hold, z3_init, self.u_max_24[dof_idx])
                cl_radius = info['cl_radius']                                                       # 閉ループのスペクトル半径
                zeta3_sim = info['xi'][:M, 5]                                                       # 内部複製が予測した ζ3 の時系列（実測 z3 と比較する量）
                r3 = z3_meas - zeta3_sim                                                            # モデルで説明できない外乱（純粋なモデル誤差指標）
                r3_rms = float(np.sqrt(np.nanmean(r3 ** 2))) if np.isfinite(r3).any() else float('nan')  # その rms

                # ---- 7. モデル妥当性ゲート（FFを更新してよいか判定する） ----
                accept_ff = True                                                                    # FF更新を採用するか
                if not (cl_radius <= CL_RHO_GATE):                                                  # 内部ADRC閉ループが発散する（NaNもここに入る）場合
                    self.get_logger().warn(
                        f"DOF {dof_idx + 1:02d}: 内部ADRC閉ループが不安定です (ρ={cl_radius:.4g})。"
                        f"同定結果が信用できないため、今回のFF更新は見送ります"
                    )
                    accept_ff = False                                                               # FFを更新しない（前回のFFを維持する）
                if z3_init is None:                                                                 # z3 を取得できなかった場合
                    self.get_logger().warn(
                        f"DOF {dof_idx + 1:02d}: z3(0⁻) を取得できませんでした。-ic·u_hold で代用せず、"
                        f"今回のFF更新は見送ります"
                    )
                    accept_ff = False                                                               # 推定値へ黙って差し替えると物理が変わったまま気付けないため

                if accept_ff:                                                                       # ゲートを通過した場合
                    self.current_ff_matrix[dof_idx] = new_ff                                        # FFパラメータを更新
                    self.prev_u_pred_full[dof_idx] = u_pred_full                                    # 次回ループ用の5次関数FF入力を保存
                    self.prev_u_ff_opt[dof_idx] = u_ff_opt                                          # 次回ループ用の u_FF_opt を保存
                    self.prev_u_opt[dof_idx] = u_opt                                                # 次回ループ用の総最適入力を保存
                    self.prev_fit_mode[dof_idx] = info['fit_mode']                                  # 次回ループ用の5次フィット経路を保存
                    z_pred, _, _ = solver.simulate_closed_loop(sys_params, adrc_params, step,       # 次回印加するFFでの予測応答
                                                               u_hold, u_pred_full, z3_init)
                    self.prev_J_pred[dof_idx] = solver.compute_J(y_tgt, z_pred + Pi - Pf)           # モデルが予測する次回の J_eval
                else:                                                                               # ゲートで弾かれた場合
                    self.prev_J_pred[dof_idx] = None                                                # 予測値は無効（次回のρ_tr判定をスキップさせる）
                self.prev_J_meas[dof_idx] = J_meas                                                  # 今回の実測 J_eval を保存

                if np.isfinite(kick_ratio[dof_idx]) and abs(kick_ratio[dof_idx] - 1.0) > ADRC_KICK_WARN:  # 比例キックが理論値から外れている場合
                    self.get_logger().warn(
                        f"DOF {dof_idx + 1:02d}: 目標値切替時の比例キックが理論値の "
                        f"{kick_ratio[dof_idx]:.2f} 倍です。ADRC_KP / ADRC_INPUT_COEF の表が"
                        f"実機のゲインと食い違っている可能性があります"
                    )
                if np.isfinite(z3_init if z3_init is not None else np.nan):                         # z3(0⁻) を取得できた場合はゲイン表の検算を行う
                    z3_theory = -ADRC_INPUT_COEF[dof_idx] * u_hold                                  # 平衡を仮定した理論値 -ic·u_hold
                    if abs(z3_theory) > 1.0 and abs(z3_init / z3_theory - 1.0) > ADRC_KICK_WARN:    # 理論値から大きく外れている場合
                        self.get_logger().warn(
                            f"DOF {dof_idx + 1:02d}: z3(0⁻) = {z3_init:.3e} が -ic·u_hold = {z3_theory:.3e} の "
                            f"{z3_init / z3_theory:.2f} 倍です。ADRC_INPUT_COEF の表を確認してください"
                        )

                self.get_logger().info(                                                             # この自由度の結果をログに出す
                    f"DOF {dof_idx + 1:02d}: J={J_meas:.1f}  ρ(A_cl)={cl_radius:.5f}  k_s={info['k_s']}"
                    f"  U_max={self.u_max_24[dof_idx]:.1f}  fit={info['fit_mode']}"
                    f"  極値 ({extrema[0]:.3f}, {extrema[1]:+.2f}) / ({extrema[2]:.3f}, {extrema[3]:+.2f})"
                    f"  {'採用' if accept_ff else '見送り'}"
                )

                # 記録用データを保存（ビューア用スナップショットとデバッグExcelの両方がこれを使う）
                snap_dof.append(self.make_snap_entry(
                    dof_idx, dof_map, M, raw_y, y_gap, Pi, Pf,
                    ff_used_this_iteration[dof_idx], used_extrema_list[dof_idx],
                    y_sys=y_sys_sim + Pf, y_tgt=y_tgt + Pf,
                    u_ff_opt_used=u_ff_opt_used, u_opt_used=u_opt_used, u_ff_applied=u_ff,
                    tgt_id=list(tgt_params), sys_id=list(sys_params),
                    tgt_used=tgt_used, sys_used=sys_used,
                    J=J_meas, fit_res=float(np.nansum((u_ff - u_ff_opt_used) ** 2)),
                    fit_mode=mode_used, id_res_sys=float(np.sum((y_sys_sim - y_shifted) ** 2)),
                    u_adrc_meas=u_adrc_meas, u_adrc_cl=u_adrc_cl,
                    adrc_res=adrc_res, adrc_res_open=adrc_res_open,
                    adrc_kick=kick_ratio[dof_idx], adrc_delay=kick_delay[dof_idx],
                    cl_radius=cl_radius, cl_ok=float(cl_ok),
                    z3_meas=z3_meas, zeta3_sim=zeta3_sim, r3_rms=r3_rms,
                    k_s=info['k_s'], u_max=self.u_max_24[dof_idx], rho_tr=rho_tr,
                    accept=float(accept_ff)))

            # ---- 内側ループの判定 ----
            if self.min_J_sum == float('inf'):                                                      # 初回の場合
                diff_msg = "(初回)"
            else:                                                                                   # 2回目以降
                diff = J_sum - self.min_J_sum                                                       # これまでのベストJと比較
                diff_msg = f"(これまでのベストより {-diff:.2f} 改善！)" if diff < 0 else f"(これまでのベストより {diff:.2f} 悪化)"

            self.get_logger().info(
                f"内側ループ {self.current_inner + 1} 完了: 今回のJ = {J_sum:.2f}, "
                f"これまでのベストJ = {self.min_J_sum if self.min_J_sum != float('inf') else J_sum:.2f} {diff_msg}"
            )

            if J_sum < self.min_J_sum:                                                              # ベストかどうか判定
                self.min_J_sum = J_sum                                                              # ベストJ更新
                self.best_ff_matrix = [row[:] for row in ff_used_this_iteration]                    # ベストFFパラメータを格納
                self.best_extrema = list(used_extrema_list)                                         # ベストJのときの極値を保存

            self.current_inner += 1                                                                 # 内側ループ回数更新

            if ENABLE_SNAPSHOT:                                                                     # ビューア用スナップショットを書き出す
                self.save_snapshot(snap_dof, J_sum)

            # ---- 内側ループ終了判定 ----
            if J_sum < self.threshold_J or self.current_inner >= self.max_inner_iter:                # Jが閾値より小さくなったか、最大回数を超えたか
                self.get_logger().info(f"外側ループ {self.current_outer + 1} 完了！最良結果をCSVに保存します。")
                self.save_optimal_results_to_csv()                                                  # ベストFF入力の情報をCSVへ保存
                if DEBUG_EXCEL:                                                                     # デバッグExcelへこの外側ループぶんのシートを追加する
                    self.save_debug_to_excel(snap_dof, J_sum)                                       # 内側ループ終了時（＝外側ループ終了時）の結果を貼る
                self._print_best_params()                                                           # 最良パラメータを表示

                self.current_outer += 1                                                             # 外側ループ回数を更新
                self.current_inner = 0                                                              # 内側ループ回数を0に戻す
                self.min_J_sum = float('inf')                                                       # 内側ループの評価関数値の初期値へ戻す

                if self.current_outer >= self.max_outer_iter:                                       # 外側ループを終えた後の判定
                    self.state = "FINISHED"                                                         # 終了状態に変更
                    self.state_start_time = self.get_clock().now()                                  # 現在時刻を取得
                    return                                                                          # パイプラインを終了

                self.initial_pot = list(self.target_pot)                                            # 1つ前の目標値を次の初期姿勢にする（姿勢ごとの局所線形化を進める）
                self.target_pot = self.get_next_target_positions()                                  # 次の目標値を決める
                self.current_ff_matrix = self.build_initial_ff_matrix()                             # FFパラメータを初回励振用の非ゼロ初期値へリセット
                self.prev_u_pred_full = [None] * N_DOF_ALL                                          # FFリセットに伴い前回入力もリセット
                self.prev_u_ff_opt = [None] * N_DOF_ALL                                             # FFリセットに伴い前回の u_FF_opt もリセット
                self.prev_u_opt = [None] * N_DOF_ALL                                                # FFリセットに伴い前回の総最適入力もリセット
                self.prev_J_meas = [None] * N_DOF_ALL                                               # トラストリージョンの判定もやり直す
                self.prev_J_pred = [None] * N_DOF_ALL                                               # 同上
                self.u_max_24 = [U_MAX_INIT] * N_DOF_ALL                                            # FF振幅の上限も初期値へ戻す
                self.param_history = []                                                             # ビューアの横軸を新しい外側ループの内側ループ番号に戻す

            self.state = "INIT_ROBOT"                                                               # 初期状態に戻す
            self.state_start_time = self.get_clock().now()                                          # 現在時刻を取得

        except Exception as exc:                                                                    # 何かエラーが出たときの処理
            self.get_logger().error(f"最適化パイプライン異常: {exc}\n{traceback.format_exc()}")
            self.state = "FINISHED"
            self.state_start_time = self.get_clock().now()

    # ビューア用データ1自由度分を作る関数（未計算項目はNaNで埋める）
    def make_snap_entry(self, dof_idx, dof_map, M, raw_y, y_gap, Pi, Pf, ff, extrema, **kw):        # 引数(自由度番号, 対応表, サンプル数, 実測POT, 欠測マスク, 初期位置, 目標位置, 印加FF, その極値, 計算できた項目)
        """最適化対象外の自由度でも同じキーをそろえて返す。

        データ構造（24自由度分の並び）を保ったまま未計算項目を NaN で埋めるので、ビューアは
        表示枠を維持したまま実測POT値だけを描ける。
        """
        nan_t = np.full(M, np.nan)                                                                  # 時系列のNaN埋め
        return {
            'y_data': raw_y,                                                                        # 実測POT値
            'y_gap': y_gap,                                                                         # 実測が無く補間の直線になっている区間
            'y_sys': kw.get('y_sys', nan_t),                                                        # 今回同定したシステムモデルの応答
            'y_tgt': kw.get('y_tgt', nan_t),                                                        # 今回同定した目標モデルの応答
            'u_ff_opt_used': kw.get('u_ff_opt_used', nan_t),                                        # 今回印加したFFの元になった u_FF_opt
            'u_opt_used': kw.get('u_opt_used', nan_t),                                              # そのときELが想定した総最適入力
            'u_ff_applied': kw.get('u_ff_applied', np.zeros(M)),                                    # 今回ロボットへ送信した5次関数FF入力
            'tgt_params_id': kw.get('tgt_id', [np.nan] * 2),                                        # 今回同定した目標モデル[T1, wn]
            'sys_params_id': kw.get('sys_id', [np.nan] * 4),                                        # 今回同定したシステムモデル[T1, zeta, wn, b0]
            'tgt_params_used': kw.get('tgt_used', [np.nan] * 2),                                    # 今回のFFを作るのに使った目標モデル
            'sys_params_used': kw.get('sys_used', [np.nan] * 4),                                    # 今回のFFを作るのに使ったシステムモデル
            'ff': list(ff),                                                                         # 今回印加したFFパラメータ[a,b,c,d,e]
            'extrema': list(extrema),                                                               # 今回印加したFFの極値[t1,y1,t2,y2]
            'J': float(kw.get('J', np.nan)),                                                        # このDOFの評価関数値（実測と目標モデルの差）
            'Pi': float(Pi), 'Pf': float(Pf),                                                       # 初期位置・目標位置
            'pot_idx': dof_map[dof_idx],                                                            # 26要素配列でのインデックス
            'opt': float(OPT_DOF_MASK[dof_idx]),                                                    # 最適化対象の自由度か（1/0）
            'fit_res': float(kw.get('fit_res', np.nan)),                                            # 印加したFFの近似残差 Σ(FF-u_FF_opt)²
            'fit_mode': int(kw.get('fit_mode', -2)),                                                # 5次フィットの経路（0=L²射影, 1=退避, -1=失敗, -2=該当なし, -3=f≡0）
            'id_res_sys': float(kw.get('id_res_sys', np.nan)),                                      # システムモデル同定の残差
            'u_adrc_meas': kw.get('u_adrc_meas', nan_t),                                            # 実測ADRC出力 u_pwm - u_ff（絶対PWM）
            'u_adrc_cl': kw.get('u_adrc_cl', nan_t),                                                # 内部複製が出した u_ADRC（上と一致すべき量）
            'adrc_res': float(kw.get('adrc_res', np.nan)),                                          # 内部ADRCと実測PWMの残差rms [PWM]
            'adrc_res_open': float(kw.get('adrc_res_open', np.nan)),                                # 仕上げ前の同じ残差
            'adrc_kick': float(kw.get('adrc_kick', np.nan)),                                        # 比例キック 実測/理論（ゲイン表の整合）
            'adrc_delay': float(kw.get('adrc_delay', np.nan)),                                      # この自由度で検出した通信遅れ[サンプル]
            'cl_radius': float(kw.get('cl_radius', np.nan)),                                        # 内部ADRC閉ループのスペクトル半径
            'cl_ok': float(kw.get('cl_ok', np.nan)),                                                # 閉ループ同定の仕上げを採用したか（1/0）
            'z3_meas': kw.get('z3_meas', nan_t),                                                    # 実測 z3（ESO外乱推定値）
            'zeta3_sim': kw.get('zeta3_sim', nan_t),                                                # 内部複製が予測した ζ3（上と一致すべき量）
            'r3_rms': float(kw.get('r3_rms', np.nan)),                                              # r3 = z3_meas - ζ3_sim の rms（モデル誤差指標）
            'k_s': float(kw.get('k_s', np.nan)),                                                    # Q_k の切替インデックス（目標軌道の整定時刻）
            'u_max': float(kw.get('u_max', np.nan)),                                                # FF振幅の上限（トラストリージョン）
            'rho_tr': float(kw.get('rho_tr', np.nan)),                                              # トラストリージョン比（実測の改善 / 予測した改善）
            'accept': float(kw.get('accept', np.nan)),                                              # この自由度のFF更新を採用したか（1/0）
        }

