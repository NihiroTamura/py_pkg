#       J = Σ_{k=0}^{M-1} e_k^T Q_k e_k + R Σ_{k<N_ff} u_k^2 + R_du Σ_{k=0}^{N_ff} (Δu_k)^2
#       e_k = x_sys(k) - x_tgt(k)（位置・速度・加速度の誤差）, u_k = u_FF(k), Δu_k = u_k - u_{k-1}
